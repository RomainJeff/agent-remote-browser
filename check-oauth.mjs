// In-memory client, isolated temporary gateway state, no Docker calls or real profiles.
import assert from 'node:assert/strict';
import http from 'node:http';
import {once} from 'node:events';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {randomBytes,createHash} from 'node:crypto';
const dir = mkdtempSync(tmpdir()+'/ac-oauth-');
process.env.STATE_FILE=dir+'/state';
process.env.LOGIN_KEY_FILE=dir+'/key';
const {oauth}=await import('./oauth.mjs');
const {state,principalFor}=await import('./store.mjs');
const {hash}=await import('./policy.mjs');
const token = randomBytes(32).toString('hex');
state.profiles.fixture={tokenHash:hash(token)};
const server=http.createServer((req,res)=>oauth(req,res,{audit(){}}).catch(()=>res.writeHead(500).end()));
server.listen(0,'127.0.0.1');
await once(server,'listening');
const base='http://127.0.0.1:'+server.address().port;
const post=(path,body)=>fetch(base+path,{method:'POST',redirect:'manual',headers:{'content-type':'application/json'},body:JSON.stringify(body)});
try {
  const redirect_uri='https://example.com/callback';
  const registration=await post('/register',{redirect_uris:[redirect_uri],token_endpoint_auth_method:'none'});
  assert.equal(registration.status,201);
  const {client_id}=await registration.json();
  const code_verifier=randomBytes(32).toString('base64url');
  const code_challenge=createHash('sha256').update(code_verifier).digest('base64url');
  const params=new URLSearchParams({client_id,redirect_uri,response_type:'code',code_challenge_method:'S256',code_challenge});
  const page=await fetch(base+'/authorize?'+params);
  assert.equal(page.status,200);
  assert.match(page.headers.get('content-security-policy'),/frame-ancestors 'none'/);
  const pending=(await page.text()).match(/name="pending" value="([^"]+)"/)[1];
  const consent=await post('/authorize',{pending,token});
  assert.equal(consent.status,302);
  const code=new URL(consent.headers.get('location')).searchParams.get('code');
  const grant={grant_type:'authorization_code',client_id,redirect_uri,code_verifier,code};
  const exchange=await post('/token',grant);
  assert.equal(exchange.status,200);
  const issued=await exchange.json();
  assert.ok(principalFor(issued.access_token)?.profile==='fixture');
  assert.equal((await post('/token',grant)).status,400);
  const refresh={grant_type:'refresh_token',client_id,refresh_token:issued.refresh_token};
  assert.equal((await post('/token',refresh)).status,200);
  assert.equal((await post('/token',refresh)).status,400);
  const nextPage = await fetch(base+'/authorize?'+params);
  const nextPending = (await nextPage.text()).match(/name="pending" value="([^"]+)"/)[1];
  const nextConsent = await post('/authorize',{pending:nextPending,token});
  const nextCode = new URL(nextConsent.headers.get('location')).searchParams.get('code');
  state.profiles.fixture.tokenHash = null;
  assert.equal((await post('/token',{...grant,code:nextCode})).status,400);
  console.log('Consent, PKCE exchange, replay rejection and refresh rotation passed');
} finally { server.close(); rmSync(dir,{recursive:true,force:true}); }
